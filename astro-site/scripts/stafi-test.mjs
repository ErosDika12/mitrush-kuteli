import { chromium } from 'playwright';
const base = process.argv[2];
const ip0 = process.env.PUBLIC_CHECK_IP; const b = await chromium.launch(ip0 ? { args: [`--host-resolver-rules=MAP ${new URL(base).hostname} ${ip0}`] } : {});
let fail = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail++; };
const c = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await c.newPage();
await p.goto(base + '/stafi', { waitUntil: 'networkidle' });
ok((await p.locator('.sd-chips a').allInnerTexts()).length === 6, 'six category chips');
ok((await p.locator('.sd-sec .sd-num').allInnerTexts()).join(',') === '01,02,03,04,05,06', 'sections numbered 01-06');
ok((await p.locator('#udheheqja [data-sec-count]').innerText()) === '3 anëtarë', 'section count shown');
const cols = await p.evaluate(() => getComputedStyle(document.querySelector('#udheheqja .sd-grid')).gridTemplateColumns.split(' ').length);
ok(cols === 4, 'desktop grid has 4 columns (' + cols + ')');
ok(await p.evaluate(() => getComputedStyle(document.getElementById('sd-bar')).position === 'sticky'), 'search bar is sticky on desktop');
await p.locator('.sd-chips a', { hasText: 'Psikologia' }).click(); await p.waitForTimeout(1800);
const pos = await p.evaluate(() => ({ s: document.getElementById('psikologia').getBoundingClientRect().top, bar: document.getElementById('sd-bar').getBoundingClientRect().bottom }));
ok(pos.s >= pos.bar - 1 && pos.s < pos.bar + 120, `anchored section starts below the sticky bar (${Math.round(pos.s)} >= ${Math.round(pos.bar)})`);
await p.fill('#f-q', 'matem'); 
ok((await p.locator('[data-person]:visible').count()) === 2 && (await p.locator('#lendore [data-sub-count], #lendore [data-block-count]:visible').first().innerText()) === '2', 'search "matem" shows 2 people and block count 2');
await p.fill('#f-q', ''); await p.selectOption('#f-grupi', 'psikologia');
ok((await p.locator('[data-person]:visible').count()) === 1, 'category filter psikologia shows 1');
await p.selectOption('#f-grupi', 'teknik');
ok((await p.locator('[data-note]:visible').count()) === 1 && (await p.locator('#staff-empty').isHidden()), 'teknik shows its note, not the empty state');
await b.close(); console.log(fail ? 'STAFI FAIL ' + fail : 'STAFI OK'); process.exit(fail ? 1 : 0);
